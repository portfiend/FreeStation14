using Content.Shared._CP14.Workbench.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._CP14.Workbench.UserInterface;

/// <summary>
///     Box containing information about an entity produced by a workbench recipe.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WorkbenchRecipeResultInfo : BoxContainer
{
    private IPrototypeManager _protoMan = default!;

    public WorkbenchRecipeResultInfo()
    {
        RobustXamlLoader.Load(this);

        _protoMan = IoCManager.Resolve<IPrototypeManager>();
    }

    /// <summary>
    ///     Sets the workbench recipe prototype displayed on this info panel.
    /// </summary>
    public void SetPrototype(WorkbenchRecipePrototype? proto)
    {
        if (proto == null)
        {
            ResultEntityView.SetPrototype(null);
            ResultName.SetMessage("");
            ResultDescription.SetMessage("");
            return;
        }

        var ent = _protoMan.Index(proto.Result);
        var entName = ent.Name;

        // Name formatting
        // Include  count in name if its more than 1
        var nameMsg = new FormattedMessage();
        nameMsg.AddMarkupPermissive(Loc.GetString("workbench-ui-result-name",
            ("result", entName),
            ("count", proto.ResultCount)));

        // Description formatting
        var descMsg = new FormattedMessage();
        descMsg.AddMarkupPermissive(ent.Description);

        ResultEntityView.SetPrototype(proto.Result);
        ResultName.SetMessage(nameMsg);
        ResultDescription.SetMessage(descMsg);
    }
}
