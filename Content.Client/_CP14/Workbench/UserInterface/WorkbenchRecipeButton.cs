using Content.Shared._CP14.Workbench;
using Content.Shared._CP14.Workbench.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._CP14.Workbench.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class WorkbenchRecipeButton : Button
{
    [Dependency] private IPrototypeManager _prototype = default!;

    /// <summary>
    ///     Action fired when a recipe button is clicked (selected).
    /// </summary>
    public event Action<WorkbenchUiRecipesEntry, WorkbenchRecipePrototype>? OnSelect;

    /// <summary>
    ///     A class added to workbench recipe buttons when they are uncraftable.
    /// </summary>
    public static readonly string UncraftableClass = "Uncraftable";

    private readonly WorkbenchRecipePrototype _recipePrototype;
    private readonly bool _craftable;

    public WorkbenchRecipeButton(WorkbenchUiRecipesEntry entry)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _recipePrototype = _prototype.Index(entry.ProtoId);
        _craftable = entry.Craftable;

        OnPressed += _ => OnSelect?.Invoke(entry, _recipePrototype);

        UpdateClass();
        UpdateView();
    }

    private void UpdateClass()
    {
        var hasClass = HasStyleClass(UncraftableClass);
        if (!_craftable == hasClass)
            return;

        if (_craftable)
            RemoveStyleClass(UncraftableClass);
        else
            AddStyleClass(UncraftableClass);
    }

    private void UpdateView()
    {
        View.SetPrototype(_recipePrototype.Result);
    }
}
