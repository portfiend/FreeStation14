using Content.Shared._CP14.Workbench;
using Content.Shared._CP14.Workbench.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._CP14.Workbench.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class WorkbenchRecipeControl : Control
{
    [Dependency] private IPrototypeManager _prototype = default!;

    public event Action<WorkbenchUiRecipesEntry, WorkbenchRecipePrototype>? OnSelect;

    private readonly WorkbenchRecipePrototype _recipePrototype;
    private readonly bool _craftable;

    public WorkbenchRecipeControl(WorkbenchUiRecipesEntry entry)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _recipePrototype = _prototype.Index(entry.ProtoId);
        _craftable = entry.Craftable;

        Button.OnPressed += _ => OnSelect?.Invoke(entry, _recipePrototype);

        UpdateColor();
        UpdateView();
    }

    private void UpdateColor()
    {
        if (_craftable)
            Button.ModulateSelfOverride = Color.FromHex("#302622");
    }

    private void UpdateView()
    {
        View.SetPrototype(_recipePrototype.Result);
    }
}
