using Content.Shared._CP14.Workbench;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._CP14.Workbench.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class WorkbenchRequirementControl : Control
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;

    public WorkbenchRequirementControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entity.System<SpriteSystem>();
    }

    public WorkbenchRequirementControl(WorkbenchCraftRequirement requirement) : this()
    {
        var title = new FormattedMessage();
        title.AddMarkupPermissive(requirement.GetRequirementTitle(_proto));
        NameLabel.SetMessage(title);

        var texture = requirement.GetRequirementTexture(_proto);
        if (texture is not null)
        {
            View.Visible = true;
            View.Texture = _sprite.Frame0(texture);
            View.Modulate = requirement.GetRequirementColor(_proto);
        }

        var entityView = requirement.GetRequirementEntityView(_proto);
        if (entityView is not null)
        {
            EntityView.Visible = true;
            EntityView.Modulate = requirement.GetRequirementColor(_proto);
            EntityView.SetPrototype(entityView);
        }
    }
}
