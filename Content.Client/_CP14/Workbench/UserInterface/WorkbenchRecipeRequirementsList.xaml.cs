
using Content.Shared._CP14.Workbench.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._CP14.Workbench.UserInterface;

/// <summary>
///     Box containing information about an entity produced by a workbench recipe.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WorkbenchRecipeRequirementsList : PanelContainer
{
    public WorkbenchRecipeRequirementsList()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetRequirements(WorkbenchRecipePrototype? proto)
    {
        RequirementListBox.RemoveAllChildren();

        if (proto == null)
            return;

        foreach (var req in proto.Requirements)
        {
            var reqControl = new WorkbenchRequirementControl(req);
            RequirementListBox.AddChild(reqControl);
        }
    }
}
