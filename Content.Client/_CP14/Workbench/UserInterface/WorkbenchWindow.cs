using System.Linq;
using Content.Shared._CP14.Workbench;
using Content.Shared._CP14.Workbench.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._CP14.Workbench.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class WorkbenchWindow : DefaultWindow
{
    private const int AllCategoryId = -1;

    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private ILogManager _log = default!;

    public event Action<WorkbenchUiRecipesEntry>? OnCraft;

    /// <summary>
    /// Used for category dropdown filtering.
    /// </summary>
    private readonly Dictionary<int, ProtoId<WorkbenchRecipeCategoryPrototype>> _categoryIndexes = new();
    private HashSet<WorkbenchUiRecipesEntry> _cachedRecipes = new();

    private List<WorkbenchUiRecipeCategory> _categories = new();
    private List<WorkbenchUiRecipesEntry> _uncategorized = new();

    private WorkbenchUiRecipesEntry? _selectedEntry;
    private string _searchFilter = string.Empty;

    private ISawmill Sawmill { get; init; }

    public WorkbenchWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Sawmill = _log.GetSawmill("workbench_window");

        SearchBar.OnTextChanged += OnSearchChanged;
        CraftButton.OnPressed += OnCraftPressed;
        OptionCategories.OnItemSelected += OnCategoryItemSelected;
    }

    private void UpdateRecipesVisibility()
    {
        CraftsContainer.RemoveAllChildren();

        if (_cachedRecipes.Count == 0)
            return;

        var hasIndex = _categoryIndexes.TryGetValue(OptionCategories.SelectedId, out var selectedCategory);
        var isAll = OptionCategories.SelectedId == AllCategoryId;

        if (_uncategorized.Count > 0 && isAll)
        {
            var uncategorizedGridContainer = new GridContainer
            {
                Columns = 5,
                VerticalExpand = true
            };

            CraftsContainer.AddChild(uncategorizedGridContainer);
            AddRecipeListToGrid(_uncategorized, uncategorizedGridContainer);
        }

        foreach (var category in _categories)
        {
            if (hasIndex && category.ID != selectedCategory)
                continue;

            var categoryLabel = new RichTextLabel
            {
                Margin = new Thickness(5),
                Text = category.Name
            };
            CraftsContainer.AddChild(categoryLabel);

            var gridContainer = new GridContainer
            {
                Columns = 5,
                VerticalExpand = true
            };
            CraftsContainer.AddChild(gridContainer);

            AddRecipeListToGrid(category.Recipes, gridContainer);
        }

        if (_selectedEntry is not null && !_cachedRecipes.Contains(_selectedEntry.Value))
            RecipeSelectNull();
    }

    private void AddRecipeListToGrid(List<WorkbenchUiRecipesEntry> category, GridContainer gridContainer)
    {
        foreach (var entry in category)
        {
            if (!_prototype.TryIndex(entry.ProtoId, out var indexedEntry))
            {
                Sawmill.Error($"No recipe prototype {entry.ProtoId} retrieved from cache found");
                continue;
            }

            if (!ProcessSearchFilter(entry, indexedEntry))
                continue;

            if (!ProcessSearchCategoryFilter(indexedEntry))
                continue;

            var control = new WorkbenchRecipeButton(entry);
            control.OnSelect += RecipeSelect;

            gridContainer.AddChild(control);
        }
    }

    public void UpdateRecipes(List<WorkbenchUiRecipesEntry> recipes)
    {
        if (_player.LocalEntity is null)
            return;

        _cachedRecipes = recipes.ToHashSet();
        _categoryIndexes.Clear();
        _categories.Clear();
        _uncategorized.Clear();
        OptionCategories.Clear();
        OptionCategories.AddItem(Loc.GetString("workbench-recipe-category-all"), AllCategoryId);

        // Sort all recipes by priority and category.
        var sortedRecipes = recipes
            .OrderByDescending(e => e.Craftable)
            .ThenByDescending(e =>
            {
                if (!_prototype.TryIndex(e.ProtoId, out WorkbenchRecipePrototype? recipe))
                    return 0;
                return recipe.Priority;
            })
            .ThenBy(e =>
            {
                if (!_prototype.TryIndex(e.ProtoId, out WorkbenchRecipePrototype? recipe) ||
                    !_prototype.TryIndex(recipe.Category, out WorkbenchRecipeCategoryPrototype? category))
                    return string.Empty;
                return category.ID;
            });

        // Assign recipes to uncategorized and categorized lists.
        var unsortedCategories = new Dictionary<ProtoId<WorkbenchRecipeCategoryPrototype>, List<WorkbenchUiRecipesEntry>>();
        foreach (var entry in sortedRecipes)
        {
            if (!_prototype.TryIndex(entry.ProtoId, out var indexedEntry))
                continue;

            if (!_prototype.TryIndex(indexedEntry.Category, out var indexedCategory))
            {
                _uncategorized.Add(entry);
                continue;
            }

            if (!unsortedCategories.TryGetValue(indexedCategory.ID, out var entries))
            {
                entries = new List<WorkbenchUiRecipesEntry>();
                unsortedCategories[indexedCategory.ID] = entries;
            }

            entries.Add(entry);
        }

        // Sort categories by priority.
        _categories = unsortedCategories
            .Select(c =>
            {
                _prototype.TryIndex(c.Key, out var category);
                var id = c.Key;
                var priority = category?.Priority ?? 0;
                var name = category != null ? Loc.GetString(category.Name) : c.Key.ToString();
                var recipes = c.Value;

                return new WorkbenchUiRecipeCategory(id, priority, name, recipes);
            })
            .OrderByDescending(c => c.Priority)
            .ToList();

        var count = 0;
        foreach (var category in _categories)
        {
            OptionCategories.AddItem(category.Name, count);
            _categoryIndexes.Add(count, category.ID);
            count++;
        }

        UpdateRecipesVisibility();
    }

    private void OnSearchChanged(LineEdit.LineEditEventArgs _)
    {
        _searchFilter = SearchBar.Text.Trim().ToLowerInvariant();
        UpdateRecipesVisibility();
    }

    private void OnCraftPressed(BaseButton.ButtonEventArgs _)
    {
        if (_selectedEntry is null)
            return;

        OnCraft?.Invoke(_selectedEntry.Value);
    }

    private void OnCategoryItemSelected(OptionButton.ItemSelectedEventArgs obj)
    {
        OptionCategories.SelectId(obj.Id);
        UpdateRecipesVisibility();
    }

    private bool ProcessSearchFilter(WorkbenchUiRecipesEntry entry, WorkbenchRecipePrototype indexedEntry)
    {
        if (_searchFilter == string.Empty)
            return true;

        // Skip the iteration, because the desired result does not match the filter
        if (_prototype.TryIndex(indexedEntry.Result, out var indexedResult))
            return indexedResult.Name.Contains(_searchFilter);

        Sawmill.Error($"No result entity prototype {entry.ProtoId} retrieved from cache found");
        return false;
    }

    private bool ProcessSearchCategoryFilter(WorkbenchRecipePrototype indexedEntry)
    {
        // If we are searching through all categories, we simply skip the current filter
        if (OptionCategories.SelectedId == AllCategoryId)
            return true;

        if (!_categoryIndexes.TryGetValue(OptionCategories.SelectedId, out var selectedCategory))
        {
            Sawmill.Error($"Non-existent {OptionCategories.SelectedId} category id selected. Filter skipped");
            return true;
        }

        if (indexedEntry.Category is null)
            return false;

        if (!_prototype.TryIndex(indexedEntry.Category, out var indexedCategory))
        {
            Sawmill.Error($"Non-existent {indexedEntry.Category} category prototype id. Filter skipped");
            return true;
        }

        return indexedCategory.ID == selectedCategory;
    }

    private void RecipeSelect(WorkbenchUiRecipesEntry entry, WorkbenchRecipePrototype recipe)
    {
        _selectedEntry = entry;

        var result = _prototype.Index(recipe.Result);

        // TODO: Make it through the localization?
        var counter = recipe.ResultCount > 1 ? $" x{recipe.ResultCount}" : string.Empty;

        ItemView.SetPrototype(recipe.Result);
        ItemName.Text = result.Name + counter;
        ItemDescription.Text = result.Description;
        ItemRequirements.RemoveAllChildren();

        foreach (var requirement in recipe.Requirements)
        {
            ItemRequirements.AddChild(new WorkbenchRequirementControl(requirement));
        }

        CraftButton.Disabled = !entry.Craftable;
    }

    private void RecipeSelectNull()
    {
        _selectedEntry = null;

        ItemView.SetPrototype(null);
        ItemName.Text = string.Empty;
        ItemDescription.Text = string.Empty;
        ItemRequirements.RemoveAllChildren();
        CraftButton.Disabled = true;
    }

    private sealed partial class WorkbenchUiRecipeCategory(ProtoId<WorkbenchRecipeCategoryPrototype> id,
        int priority,
        string name,
        List<WorkbenchUiRecipesEntry> recipes)
    {
        public ProtoId<WorkbenchRecipeCategoryPrototype> ID = id;
        public int Priority = priority;
        public string Name = name;
        public List<WorkbenchUiRecipesEntry> Recipes = recipes;
    }
}
